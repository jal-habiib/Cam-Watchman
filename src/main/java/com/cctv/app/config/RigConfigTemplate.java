package com.cctv.app.config;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Writes a ready-to-run {@code cameras.properties} that points at the MediaMTX test rig
 * ({@code rig/start-rig.ps1}). Used by the first-run screen so a fresh checkout can display
 * something without editing URLs by hand.
 */
public final class RigConfigTemplate {

    public static final String RTSP_BASE = "rtsp://127.0.0.1:8554";

    private RigConfigTemplate() {
    }

    public static String propertiesText() {
        return """
                # Generated by Cam Watchman: MediaMTX test rig (rig/start-rig.ps1).
                # Each camera has an independent main-stream AI + recording pipeline and a display substream.
                cameras.1.id=1
                cameras.1.name=Rig cam 1
                cameras.1.url=%1$s/cam1_main
                cameras.1.substream_url=%1$s/cam1_sub
                cameras.1.record=true
                cameras.1.ai=true

                cameras.2.id=2
                cameras.2.name=Rig cam 2
                cameras.2.url=%1$s/cam2_main
                cameras.2.substream_url=%1$s/cam2_sub
                cameras.2.record=true
                cameras.2.ai=true

                cameras.3.id=3
                cameras.3.name=Rig cam 3
                cameras.3.url=%1$s/cam3_main
                cameras.3.substream_url=%1$s/cam3_sub
                cameras.3.record=true
                cameras.3.ai=true

                cameras.4.id=4
                cameras.4.name=Rig cam 4
                cameras.4.url=%1$s/cam4_main
                cameras.4.substream_url=%1$s/cam4_sub
                cameras.4.record=true
                cameras.4.ai=true

                # Defaults are fine for the rig; change for a real deployment.
                recording.segment.seconds=15
                retention.days=7
                retention.size.gb=40
                retention.min.free.gb=10
                ai.rate.fps=1
                """.formatted(RTSP_BASE);
    }

    /** Writes the template, creating parent directories, and returns the file written. */
    public static Path write(Path configFile) throws IOException {
        Path parent = configFile.toAbsolutePath().getParent();
        if (parent != null) {
            Files.createDirectories(parent);
        }
        Files.writeString(configFile, propertiesText(), StandardCharsets.UTF_8);
        return configFile;
    }
}
